import { expect, test } from '@playwright/test'
import path from 'node:path'

test('真实服务：选择三份合同、证据链、导出与手机布局', async ({ page }) => {
  test.skip(!process.env.REPORT_ACCEPTANCE_LIVE, '仅显式验收真实服务时运行')
  test.setTimeout(90000)
  const issues: string[] = []
  page.on('pageerror', error => issues.push(error.message))
  await page.goto('/login')
  await page.locator('input[name="username"]').fill('admin')
  await page.locator('input[name="password"]').fill('admin123')
  await page.getByRole('button', { name: '登 录' }).click()
  await expect(page).not.toHaveURL(/login/)
  const token = await page.evaluate(() => localStorage.getItem('token'))
  const metadata = await page.request.get('/api/v1/reports/contracts-metadata', { headers: { Authorization: `Bearer ${token}` } })
  expect(metadata.ok()).toBe(true)
  const contracts = await metadata.json()
  const selected = contracts.filter((c: { job_status: string; risk_total: number }) => ['done', 'review_required'].includes(c.job_status) && c.risk_total > 0).slice(0, 3)
  expect(selected).toHaveLength(3)
  const expectedResponse = await page.request.post('/api/v1/reports/preview', { headers: { Authorization: `Bearer ${token}` }, data: { contract_ids: selected.map((c: { id: number }) => c.id) } })
  expect(expectedResponse.ok()).toBe(true)
  const expectedSnapshot = await expectedResponse.json()
  const output = path.resolve('../outputs/live-dashboard')
  await page.goto('/reports')
  await expect(page.getByTestId('preview-total')).toHaveText(String(contracts.length))
  await expect(page.locator('.chart canvas')).toHaveCount(4)
  await expect(page.locator('.report-body .el-loading-mask')).toHaveCount(0)
  await page.waitForLoadState('networkidle')
  await page.screenshot({ path: path.join(output, 'reports-default.png') })
  await page.getByRole('button', { name: '选择合同', exact: true }).click()
  for (const contract of selected) {
    await page.getByLabel('搜索合同').fill(contract.filename)
    await page.locator(`input[data-contract-id="${contract.id}"]`).check()
  }
  await expect(page.getByTestId('preview-total')).toHaveText('3')
  await expect(page.locator('.chart canvas')).toHaveCount(4)
  await page.getByLabel('搜索合同').clear()
  await page.waitForLoadState('networkidle')
  await page.getByRole('button', { name: '收起合同列表', exact: true }).click()
  await expect(page.locator('.report-body .el-loading-mask')).toHaveCount(0)
  await page.locator('.report-heading').scrollIntoViewIfNeeded()
  await page.screenshot({ path: path.join(output, 'reports-desktop.png'), fullPage: true })
  await page.locator('.snapshot-heading').scrollIntoViewIfNeeded()
  await page.screenshot({ path: path.join(output, 'reports-preview.png') })
  await page.getByRole('button', { name: '查看证据', exact: true }).click()
  await expect(page.locator('.risk-evidence')).toHaveCount(expectedSnapshot.risks.length)
  await expect.poll(async () => Math.round((await page.locator('.el-drawer').boundingBox())!.x)).toBe(560)
  await page.screenshot({ path: path.join(output, 'reports-evidence.png') })
  await page.getByRole('button', { name: 'Close this dialog' }).click()
  for (const format of ['Excel', 'Word']) {
    const download = page.waitForEvent('download')
    await page.getByRole('button', { name: '导出 ' + format }).click()
    const file = await download
    expect(await file.failure()).toBeNull()
    await file.saveAs(path.join(output, 'browser-' + (format === 'Excel' ? 'selected.xlsx' : 'selected.docx')))
  }
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByRole('button', { name: '打开导航菜单' })).toBeVisible()
  await page.waitForFunction(() => document.querySelector('.shell-side')!.getBoundingClientRect().right <= 1)
  await page.locator('.reports').evaluate(element => { element.parentElement!.parentElement!.scrollLeft = 0 })
  await page.getByTestId('preview-total').scrollIntoViewIfNeeded()
  await page.screenshot({ path: path.join(output, 'reports-mobile.png') })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(await page.locator('.kpi-row').evaluate(element => element.getBoundingClientRect().left)).toBeGreaterThanOrEqual(0)
  await page.getByRole('button', { name: '选择合同', exact: true }).click()
  await page.getByLabel('搜索合同').fill(selected[0].filename)
  await page.screenshot({ path: path.join(output, 'reports-mobile-picker.png') })
  await page.getByRole('button', { name: '清空勾选' }).click()
  await expect(page.getByTestId('preview-total')).toHaveText(String(contracts.length))
  await page.locator(`input[data-contract-id="${selected[0].id}"]`).check()
  await expect(page.getByTestId('preview-total')).toHaveText('1')
  await page.getByRole('button', { name: '收起合同列表', exact: true }).click()
  await expect(page.locator('.report-body .el-loading-mask')).toHaveCount(0)
  await page.locator('.snapshot-heading').scrollIntoViewIfNeeded()
  await page.screenshot({ path: path.join(output, 'reports-mobile-single.png') })
  await page.locator('.chart-grid').scrollIntoViewIfNeeded()
  await page.screenshot({ path: path.join(output, 'reports-mobile-charts.png') })
  expect(issues).toEqual([])
})
