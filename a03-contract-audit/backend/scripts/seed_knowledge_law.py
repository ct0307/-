def seed(db, force: bool = False) -> dict:
    """导入预置知识条目。force=True 跳过去重检查（用于重建）。"""
    imported = 0
    skipped = 0
    for category, source, content in LAW_ITEMS:
        if not force:
            exists = db.query(KnowledgeChunk).filter(KnowledgeChunk.source == source).first()
            if exists:
                skipped += 1
                continue
        try:
            n = index_documents([{"category": category, "source": source, "content": content}], db=db)
            imported += n
            print(f"  ✓ [{category}] {source[:40]} → {n} 切片")
        except Exception as exc:
            print(f"  ✗ [{category}] {source[:40]} 失败: {exc}")
    return {"imported": imported, "skipped": skipped}


if __name__ == "__main__":
    import argparse
    parser = argparse.ArgumentParser(description="预置法规知识库导入脚本")
    parser.add_argument("--force", action="store_true", help="跳过去重，强制重新导入")
    args = parser.parse_args()

    print(f"开始导入，条目总数：{len(LAW_ITEMS)}")
    db = SessionLocal()
    try:
        result = seed(db, force=args.force)
    finally:
        db.close()
    print(f"\n完成：导入 {result['imported']} 个切片，跳过 {result['skipped']} 条（已存在）")
